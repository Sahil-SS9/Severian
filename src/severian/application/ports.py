from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from severian.domain.models import Collection, Memory, Observation, Scope


class CanonicalRepository(Protocol):
    def create_collection(self, collection: Collection) -> Collection: ...
    def add_observation(self, observation: Observation) -> Observation: ...
    def get_observation(self, observation_id: str) -> Observation: ...
    def list_observations(self, scope: Scope) -> list[Observation]: ...
    def revise_observation(self, observation_id: str, content: str) -> Observation: ...
    def add_memory(self, memory: Memory) -> Memory: ...
    def get_memory(self, memory_id: str) -> Memory: ...
    def export_json(self) -> str: ...
    def import_json(self, payload: str) -> None: ...
    def backup(self, destination: Path) -> None: ...


class Projection(Protocol):
    def rebuild(self, repository: CanonicalRepository) -> None: ...
    def delete(self) -> None: ...


class DerivationGateway(Protocol):
    def derive(self, content: str, *, policy: dict[str, Any]) -> list[dict[str, Any]]: ...
